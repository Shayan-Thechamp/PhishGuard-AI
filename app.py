
from pathlib import Path
import re

import joblib
import streamlit as st

# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

st.set_page_config(
    page_title="PhishGuard AI",
    page_icon="🛡️",
    layout="centered"
)

MODEL_PATH = Path("models/phishguard_model.joblib")
MAX_EMAIL_LENGTH = 100_000

# --------------------------------------------------
# 2. Load the trained model
# --------------------------------------------------

@st.cache_resource
def load_model():
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            "Trained model not found. Run train_model.py first."
        )

    # Only load the model generated by your own training script.
    return joblib.load(MODEL_PATH)


try:
    model = load_model()
except Exception as error:
    st.error(f"Could not load the model: {error}")
    st.stop()

# --------------------------------------------------
# 3. Security indicator rules
# --------------------------------------------------

URL_PATTERN = re.compile(
    r"https?://[^\s<>'\"]+|www\.[^\s<>'\"]+",
    re.IGNORECASE
)

IP_URL_PATTERN = re.compile(
    r"https?://(?:\d{1,3}\.){3}\d{1,3}",
    re.IGNORECASE
)

URGENCY_TERMS = [
    "urgent",
    "immediately",
    "act now",
    "account suspended",
    "account will be closed",
    "within 24 hours",
    "verify immediately",
    "limited time"
]

CREDENTIAL_TERMS = [
    "password",
    "login details",
    "credit card",
    "bank details",
    "social security",
    "one-time password",
    "otp",
    "verification code"
]

def inspect_email(email):
    """Identify simple text-based warning indicators."""

    text = email.lower()

    urls = URL_PATTERN.findall(email)
    indicators = []

    if urls:
        indicators.append(
            f"Contains {len(urls)} URL(s). Inspect links carefully."
        )

    if IP_URL_PATTERN.search(email):
        indicators.append(
            "Contains a URL using an IP address instead of a domain."
        )

    if any(term in text for term in URGENCY_TERMS):
        indicators.append(
            "Contains urgency or pressure-related language."
        )

    if any(term in text for term in CREDENTIAL_TERMS):
        indicators.append(
            "Mentions passwords, financial details, or verification codes."
        )

    if "!" in email:
        indicators.append(
            "Contains exclamation marks; this alone does not indicate phishing."
        )

    if not indicators:
        indicators.append(
            "No indicators from this basic rule set were detected."
        )

    return indicators

# --------------------------------------------------
# 4. Application interface
# --------------------------------------------------

st.title("🛡️ PhishGuard AI")

st.subheader("AI-Based Phishing Email Detection System")

st.write(
    "Analyze email text using a machine-learning model "
    "trained on a labeled email dataset."
)

st.info(
    "Paste email text below. Do not enter real passwords, "
    "private messages, or confidential information."
)

email_text = st.text_area(
    "Email content",
    height=250,
    placeholder=(
        "Paste the email subject and message here..."
    ),
    max_chars=MAX_EMAIL_LENGTH
)

analyze = st.button(
    "Analyze Email",
    type="primary",
    use_container_width=True
)

# --------------------------------------------------
# 5. Prediction
# --------------------------------------------------

if analyze:

    if not email_text.strip():
        st.warning("Please enter some email text first.")

    else:
        try:
            prediction = model.predict([email_text])[0]

            classes = list(model.classes_)
            probabilities = model.predict_proba([email_text])[0]

            phishing_index = classes.index("phishing")
            phishing_score = float(
                probabilities[phishing_index]
            )

            st.divider()
            st.subheader("Analysis Result")

            if prediction == "phishing":
                st.error("⚠️ Phishing pattern detected")

                st.write(
                    "The model classified this email as phishing. "
                    "Avoid clicking its links or sharing sensitive information."
                )

            else:
                st.success("No phishing pattern detected")

                st.write(
                    "The model classified this email as legitimate. "
                    "This does not guarantee that the email is safe."
                )

            st.metric(
                "Model-estimated phishing probability",
                f"{phishing_score * 100:.2f}%"
            )

            st.caption(
                "This probability is the model's estimate, not a "
                "calibrated guarantee of the email's true risk."
            )

            # Security indicators
            st.subheader("Security Indicators")

            indicators = inspect_email(email_text)

            for indicator in indicators:
                st.write(f"• {indicator}")

            st.divider()

            st.caption(
                "PhishGuard AI is an educational decision-support "
                "prototype. It does not replace professional "
                "email security tools or human verification."
            )

        except Exception as error:
            st.error(
                f"An error occurred during analysis: {error}"
            )

# --------------------------------------------------
# 6. Footer
# --------------------------------------------------

st.divider()

st.caption(
    "PhishGuard AI | Machine Learning + Cybersecurity"
)
